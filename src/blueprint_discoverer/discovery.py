"""Repository discovery and project-file edits for the folder/single-repo CLI entry points.

Discovery is deterministic: a directory is a repository when it holds `.git` (directory or file, so
worktrees and submodules count). Folders without git (plain checkouts, examples) fall back to one
repository per top-level sub-directory that contains a build manifest.
"""

from __future__ import annotations

import fnmatch
import re
from pathlib import Path

import yaml

from .cartographer.code.config import MANIFESTS
from .cartographer.code.scanner import DEFAULT_EXCLUDES
from .workspace import ProjectConfig, RepoSpec, slugify

GIT_URL_RE = re.compile(r"^(https?://|ssh://|git@|file://)|\.git$")


def _skipped(name: str) -> bool:
    return name.startswith(".") or any(fnmatch.fnmatch(name, pat) for pat in DEFAULT_EXCLUDES)


def _has_manifest(root: Path, max_depth: int = 3) -> bool:
    stack = [(root, 0)]
    while stack:
        d, depth = stack.pop()
        for child in sorted(d.iterdir()):
            if child.is_file() and any(fnmatch.fnmatch(child.name, m) for m in MANIFESTS):
                return True
            if child.is_dir() and depth < max_depth and not _skipped(child.name):
                stack.append((child, depth + 1))
    return False


def discover_repos(folder: Path, max_depth: int = 3) -> list[RepoSpec]:
    """Repositories under `folder`, with paths relative to it and names unique by construction."""
    folder = folder.resolve()
    if (folder / ".git").exists():
        return [RepoSpec(name=folder.name, path=".")]
    found: list[Path] = []
    stack = [(folder, 0)]
    while stack:
        d, depth = stack.pop()
        for child in sorted(d.iterdir()):
            if not child.is_dir() or _skipped(child.name):
                continue
            if (child / ".git").exists():
                found.append(child)  # never descend into a repository
            elif depth + 1 < max_depth:
                stack.append((child, depth + 1))
    if not found:
        found = [c for c in sorted(folder.iterdir()) if c.is_dir() and not _skipped(c.name) and _has_manifest(c)]
    specs = [RepoSpec(name=p.relative_to(folder).as_posix(), path=p.relative_to(folder).as_posix()) for p in found]
    return sorted(specs, key=lambda s: s.name)


def is_git_url(target: str) -> bool:
    return bool(GIT_URL_RE.search(target)) and not Path(target).exists()


def repo_spec_for(target: str, config: ProjectConfig, base: Path, name: str | None = None,
                  ref: str | None = None) -> RepoSpec:
    """Match `target` (configured name, local path or git URL) to a configured repository, or build a new spec."""
    for spec in config.repos:
        if target == spec.name or (spec.url and target == spec.url):
            return spec
        if spec.path and not is_git_url(target) and (base / spec.path).resolve() == Path(target).resolve():
            return spec
    if is_git_url(target):
        default = re.sub(r"\.git$", "", target.rstrip("/")).rsplit("/", 1)[-1].rsplit(":", 1)[-1]
        return RepoSpec(name=name or default, url=target, ref=ref)
    path = Path(target).resolve()
    if not path.is_dir():
        raise ValueError(f"'{target}' is neither a configured repository, a directory nor a git URL")
    try:
        rel = path.relative_to(base.resolve()).as_posix()
    except ValueError:
        rel = str(path)
    return RepoSpec(name=name or path.name, path=rel)


def _entry(spec: RepoSpec, indent: str = "  ") -> str:
    fields = [f"name: {spec.name}"]
    fields += [f"{k}: {v}" for k, v in (("path", spec.path), ("url", spec.url), ("ref", spec.ref)) if v]
    return f"{indent}- {{ " + ", ".join(fields) + " }"


def write_config(path: Path, name: str, repos: list[RepoSpec]) -> None:
    """Create a new project file. Never overwrites."""
    if path.exists():
        raise FileExistsError(path)
    if not repos:
        raise ValueError("no repositories to write")
    body = "\n".join(_entry(r) for r in repos)
    path.write_text(
        "# Blueprint Discoverer project file (generated by `blueprint discover --init`).\n"
        f"name: {slugify(name)}\n"
        f"repositories:\n{body}\n"
        "inference:\n"
        "  min_domain_score: 0.15\n"
        "  llm:\n"
        "    enabled: false          # set true + ANTHROPIC_API_KEY to enrich with Claude\n"
        "    model: claude-opus-5-5\n"
        "    effort: medium\n"
        "# Human decisions always win over inference (method = \"human\", confidence = 1.0).\n"
        "overrides:\n"
        "  classifications: {}\n"
    )


def add_repo_to_config(path: Path, spec: RepoSpec) -> bool:
    """Append `spec` to `repositories:` keeping comments and layout. Returns False when already listed."""
    if any(r.name == spec.name for r in ProjectConfig.load(path).repos):
        return False
    lines = path.read_text().splitlines()
    try:
        start = next(i for i, line in enumerate(lines) if re.match(r"^repositories:\s*(#.*)?$", line))
    except StopIteration:
        raise ValueError(f"{path}: no block-style 'repositories:' key; add the repository by hand") from None
    insert, indent = start + 1, "  "
    for i in range(start + 1, len(lines)):
        line = lines[i]
        if line.strip() and not line[0].isspace() and not line.startswith("- "):
            break
        if line.lstrip().startswith("- "):
            insert, indent = i + 1, line[: len(line) - len(line.lstrip())]
    lines.insert(insert, _entry(spec, indent))
    text = "\n".join(lines) + "\n"
    try:
        repos = (yaml.safe_load(text) or {}).get("repositories") or []
    except yaml.YAMLError:
        repos = []
    if not any(isinstance(r, dict) and r.get("name") == spec.name for r in repos):
        raise ValueError(f"{path}: could not add '{spec.name}' automatically; add it by hand")
    path.write_text(text)
    return True
